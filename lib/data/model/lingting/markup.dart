/// 灵听接口里的 `[]` **不是内容的一部分**，是「搜索命中」的标记。
///
/// 实测（2026-09-24，`/v1/search/music`）：
/// * 搜「一粒麦子」→ 歌名 `[一粒][麦子]`，繁体那首是 `[一粒][麥][子]`
///   （简繁匹配会按字拆开），伴奏那首 `[一粒][麦子]（伴奏）`；
/// * **同一首歌的详情接口回来是干净的 `一粒麦子`**；
/// * 首页热门 / 每日三十首 抽了 60 条，**一条都不带**。
///
/// 所以这条规则只在「搜索结果」那条路上会真的命中，但放在解析层统一做掉最省事：
/// 每个展示面（列表、迷你条、播放页、分享、通知）都不必各自记着去掉它。
/// 只处理半角 `[]`：接口用的就是它，全角 `［］` 在实测数据里没出现过。
library;

/// 去掉搜索命中标记 `[` `]`（标题、歌手、专辑、歌词片段都用它）
String stripLingtingMarkup(String raw) {
  if (!raw.contains('[') && !raw.contains(']')) return raw;
  return raw.replaceAll('[', '').replaceAll(']', '');
}
