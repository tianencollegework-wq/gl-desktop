/// 表情面板的数据（S4.4）。
///
/// 老端把这份清单写死在 `utils/emoji.js` 里：第一个 tab 是内置的 twitter 表情
/// （66 个，`src` 全部是 `{apiUrl}/static/img/emoji/twitter/{code}.png`），
/// 第二个 tab 是「收藏」，内容由 `/enterprise/emoji/index` 返回。
///
/// 新端有两点不同（用户 2026-09-20 的要求）：
/// * **渲染走系统表情**：码值本身就是 Unicode 码点，所以面板里画的是字符、插进输入框的
///   也是字符（见 `emoji.dart`），不再去服务端拉 png；
/// * **按分类摆**：老端只有「表情 / 收藏」两栏，66 个表情挤一屏；现在按
///   笑脸 / 手势 / 动物 / 食物 / 活动 / 旅行 / 物品 / 符号 分栏，
///   第一栏「常用」**原样照抄老端那 66 个**（顺序与码值都不动），
///   这样老用户在原来的位置上还是能点到同一个表情。
library;

/// 一个收藏表情（`/enterprise/emoji/index` 的一项）
class CustomEmoji {
  const CustomEmoji({
    required this.url,
    this.id = 0,
    this.fileId = 0,
    this.name = '',
  });

  final String url;

  /// 服务端**表情记录** id：老端表情管理页删/移动用的就是它
  /// （`delEmoji({ids: checkList})` 里塞的是 `item.id`）。
  final int id;

  /// 服务端**文件** id：发消息时带的是它（`im-input.vue::chooseDiyEmoji`）。
  /// 两个值不是一回事，别混用。
  final int fileId;

  final String name;

  factory CustomEmoji.fromJson(Map<String, dynamic> json) {
    final src = json['src'] ?? json['url'] ?? json['content'];
    return CustomEmoji(
      url: src?.toString() ?? '',
      id: int.tryParse(json['id']?.toString() ?? '') ?? 0,
      fileId: int.tryParse(json['file_id']?.toString() ?? '') ?? 0,
      name: json['name']?.toString() ?? '',
    );
  }

  Map<String, dynamic> toJson() => <String, dynamic>{
    'src': url,
    'id': id,
    'file_id': fileId,
    'name': name,
  };
}

/// 一栏表情
class EmojiCategory {
  const EmojiCategory({
    required this.name,
    required this.icon,
    required this.labelKey,
    required this.codes,
  });

  /// 标识（也用于测试与调试）
  final String name;

  /// 分类条上显示的那个字符（用这一栏里的一个代表表情）
  final String icon;

  /// 文案 key
  final String labelKey;

  /// 这一栏的码值（十六进制 Unicode 码点）
  final List<String> codes;

  int get length => codes.length;
}

